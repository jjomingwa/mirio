export const WORLDS = validateWorldDefinitions(definitions);
export const ALL_NODES = WORLDS.flatMap((world) => world.nodes);
export const NODE_BY_ID = new Map(ALL_NODES.map((stage) => [stage.id, stage]));

export function getNode(id: string): StageNode {
  const result = NODE_BY_ID.get(id);
  if (!result) throw new Error(`Unknown stage node: ${id}`);
  return result;
}

export function getWorld(id: WorldId): WorldDefinition {
  const result = WORLDS.find((world) => world.id === id);
  if (!result) throw new Error(`Unknown world: ${id}`);
  return result;
}

export function getWorldForNode(id: string): WorldDefinition {
  return getWorld(getNode(id).worldId);
}
