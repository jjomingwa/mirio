import { validateWorldDefinitions } from "./schema";
import type {
  CoursePace,
  StageKind,
  StageNode,
  ThemeId,
  WorldDefinition,
  WorldId,
} from "./types";

function node(
  worldId: WorldId,
  label: string,
  title: string,
  kind: StageKind,
  theme: ThemeId,
  pace: CoursePace,
  x: number,
  y: number,
  seed: number,
  difficulty: number,
  next: string[] = [],
  secretNext: string[] = [],
): StageNode {
  return {
    id: label,
    worldId,
    label,
    title,
    kind,
    theme,
    pace,
    position: { x, y },
    seed,
    difficulty,
    timeLimit:
      kind === "final"
        ? 540
        : kind === "fortress"
          ? 360
          : 300 + difficulty * 12,
    next,
    secretNext,
    secretExit: secretNext.length > 0,
  };
}

